def _walk(x, fix):
    if isinstance(x, str):
        for a, b in fix:
            x = x.replace(a.strip("'"), b.strip("'"))
        return x
    if isinstance(x, list):
        return [_walk(i, fix) for i in x]
    if isinstance(x, tuple):
        return tuple(_walk(i, fix) for i in x)
    if isinstance(x, dict):
        return {k: _walk(v, fix) for k, v in x.items()}
    return x


